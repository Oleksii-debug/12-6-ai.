ROOT = Path(__file__).resolve().parents[1]
TOOL = ROOT / "tools" / "materialize_d03_code_capacity_four_sources.py"


def _module():
    spec = importlib.util.spec_from_file_location("d03_four_source_materializer_tested", TOOL)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _fake_records() -> list[dict[str, Any]]:
    sizes = [85_334, 82_023, 36_123, 31_724, 25_257, 53_050, 15_837, 7_599]
    families = [
        "github:pydantic/pydantic",
        "github:pydantic/pydantic",
        "github:pydantic/pydantic",
        "github:pydantic/pydantic",
        "code.scipy.project",
        "code.scipy.project",
        "github:pandas-dev/pandas",
        "github:fastapi/typer",
    ]
    return [
        {
            "schema_version": "test-only",
            "object_id": f"object-{index}",
            "authority_source_id": None,
            "source_family": family,
            "repository": "example/project",
            "commit": "a" * 40,
            "path": f"src/object_{index}.py",
            "git_blob_sha1": f"{index + 1:040x}",
            "raw_sha256": f"{index + 1:064x}",
            "utf8_bytes": size,
            "modality": "code",
            "normalization": "STRICT_UTF8_IDENTITY_PRESERVE_V1",
            "text": f"x_{index} = {index}\n",
        }
        for index, (size, family) in enumerate(zip(sizes, families, strict=True))
    ]


def test_repository_source_authorities_are_locally_well_formed() -> None:
    mod = _module()

    pydantic = mod._read_strict(ROOT / mod.PYDANTIC_CONFIG, context="Pydantic test")
    assert pydantic["source_family"] == "github:pydantic/pydantic"
    assert len(pydantic["decisions"]) == 4
    assert sum(row["size_bytes"] for row in pydantic["decisions"]) == 235_204

    scipy = mod.load_and_validate_source_authority(ROOT / mod.SCIPY_CONFIG)
    assert scipy["candidate_raw_bytes"] == 78_307
    assert scipy["canonical_credit_bytes"] == 0

    assert mod.pandas_source_authority.validate_pandas_source_authority_files(ROOT) == []
    assert mod.typer_source_authority.validate_typer_source_authority_files(ROOT) == []


