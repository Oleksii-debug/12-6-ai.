def test_verify_code_payload_binds_bytes_blob_sha_and_python() -> None:
    mod = _module()
    raw = b"def add(left, right):\n    return left + right\n"
    result = mod._verify_code_payload(
        raw,
        path="pkg/sample.py",
        expected_bytes=len(raw),
        expected_blob=mod._git_blob_sha1(raw),
        expected_sha256=mod._sha256(raw),
    )
    assert result == {"text": raw.decode(), "raw_sha256": mod._sha256(raw)}

    with pytest.raises(mod.FourSourceMaterializationError, match="byte count drift"):
        mod._verify_code_payload(
            raw,
            path="pkg/sample.py",
            expected_bytes=len(raw) + 1,
            expected_blob=mod._git_blob_sha1(raw),
        )

    with pytest.raises(mod.FourSourceMaterializationError, match="Git blob drift"):
        mod._verify_code_payload(
            raw,
            path="pkg/sample.py",
            expected_bytes=len(raw),
            expected_blob="0" * 40,
        )

    with pytest.raises(mod.FourSourceMaterializationError, match="SHA-256 drift"):
        mod._verify_code_payload(
            raw,
            path="pkg/sample.py",
            expected_bytes=len(raw),
            expected_blob=mod._git_blob_sha1(raw),
            expected_sha256="0" * 64,
        )


def test_verify_code_payload_refuses_secret_generated_invalid_utf8_and_bad_ast() -> None:
    mod = _module()
    bad_values = [
        (b'TOKEN = "sk-' + b"a" * 32 + b'"\n', "credential pattern"),
        (b"# generated by unit test\nx = 1\n", "generated-material marker"),
        (b"x = '\xff'\n", "strict UTF-8"),
        (b"def broken(:\n    pass\n", "AST parse"),
    ]
    for raw, message in bad_values:
        with pytest.raises(mod.FourSourceMaterializationError, match=message):
            mod._verify_code_payload(
                raw,
                path="pkg/sample.py",
                expected_bytes=len(raw),
                expected_blob=mod._git_blob_sha1(raw),
            )


def test_candidate_is_deterministic_and_enforces_exact_object_and_byte_floor() -> None:
    mod = _module()
    records = _fake_records()
    first = mod._render_candidate(records)
    second = mod._render_candidate(list(reversed(records)))
    assert first == second
    assert len(first.splitlines()) == 8
    assert sum(row["utf8_bytes"] for row in records) == mod.EXPECTED_RAW_BYTES

    too_few = records[:-1]
    with pytest.raises(mod.FourSourceMaterializationError, match="object count drift"):
        mod._render_candidate(too_few)

    wrong_total = [dict(row) for row in records]
    wrong_total[0]["utf8_bytes"] += 1
    with pytest.raises(mod.FourSourceMaterializationError, match="raw byte total drift"):
        mod._render_candidate(wrong_total)

    duplicate = [dict(row) for row in records]
    duplicate[1]["raw_sha256"] = duplicate[0]["raw_sha256"]
    with pytest.raises(mod.FourSourceMaterializationError, match="exact duplicate"):
        mod._render_candidate(duplicate)


def test_receipt_is_text_free_zero_credit_and_binds_candidate() -> None:
    mod = _module()
    records = _fake_records()
    candidate = mod._render_candidate(records)
    licenses = {
        "github:pydantic/pydantic": {"license_id": "MIT", "sha256": "1" * 64},
        "code.scipy.project": {"license_id": "BSD-3-Clause", "sha256": "2" * 64},
        "github:pandas-dev/pandas": {"license_id": "BSD-3-Clause", "sha256": "3" * 64},
        "github:fastapi/typer": {"license_id": "MIT", "sha256": "4" * 64},
    }
    receipt = mod._receipt(
        records,
        licenses,
        candidate=candidate,
        execution_head="a" * 40,
    )
    assert receipt["candidate_sha256"] == mod._sha256(candidate)
    assert receipt["materialized_object_count"] == 8
    assert receipt["materialized_raw_bytes"] == 336_947
    assert receipt["content_boundary"]["receipt_contains_raw_source_text"] is False
    truth = receipt["truth_boundary"]
    assert truth["canonical_capacity_credit_bytes"] == 0
    assert truth["authorized_optimized_target_exposure"] == 0
    assert truth["training_executed"] is False
    assert truth["final_test_outcomes_read"] is False
    assert truth["paid_compute_used"] is False

    core = dict(receipt)
    identity = core.pop("receipt_identity_sha256")
    assert identity == mod._sha256(mod._canonical(core))
    serialized = json.dumps(receipt, sort_keys=True)
    for record in records:
        assert record["text"] not in serialized


def test_materialize_composes_four_disjoint_sources_without_network(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    mod = _module()
    records = _fake_records()
    licenses = [
        {"license_id": "MIT", "sha256": "1" * 64},
        {"license_id": "BSD-3-Clause", "sha256": "2" * 64},
        {"license_id": "BSD-3-Clause", "sha256": "3" * 64},
        {"license_id": "MIT", "sha256": "4" * 64},
    ]

    monkeypatch.setattr(
        mod,
        "_capture_pydantic",
        lambda *_args, **_kwargs: (records[:4], licenses[0]),
    )
    monkeypatch.setattr(
        mod,
        "_materialize_scipy",
        lambda *_args, **_kwargs: (records[4:6], licenses[1]),
    )
    monkeypatch.setattr(
        mod,
        "_materialize_pandas",
        lambda *_args, **_kwargs: ([records[6]], licenses[2]),
    )
    monkeypatch.setattr(
        mod,
        "_materialize_typer",
        lambda *_args, **_kwargs: ([records[7]], licenses[3]),
    )

    candidate, receipt = mod.materialize(
        tmp_path,
        execution_head="b" * 40,
        fetch=lambda _url, _bound: (_ for _ in ()).throw(
            AssertionError("network should not be reached")
        ),
    )
    assert len(candidate.splitlines()) == 8
    assert receipt["execution_head_sha"] == "b" * 40
    assert receipt["candidate_sha256"] == mod._sha256(candidate)


def test_create_only_output_never_overwrites(tmp_path: Path) -> None:
    mod = _module()
