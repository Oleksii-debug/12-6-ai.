CODE_SAMPLE_MANIFEST_SCHEMA = "12-6.code-source-sample-manifest.v1"
CODE_PILOT_REPORT_SCHEMA = "12-6.code-source-pilot-report.v1"
NEAR_DEDUP_AUTHORITY = (
    "LOCAL_FREE_DIAGNOSTIC_ONLY_PRODUCTION_USES_D03_DATATROVE_MINHASH_0.10.0"
)

