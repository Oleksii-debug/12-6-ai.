"""Rights-aware, format-preserving code-source intake for Base pretraining.

This module is deliberately an intake adapter, not a code-specific training path.
It preserves upstream UTF-8 source text exactly, delegates source-rights authority
to D03, and hands eligible code to the incumbent DATA-10 mixture contract.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import asdict, dataclass
from pathlib import PurePosixPath
from typing import Any, Iterable, Mapping, Sequence

