"""Reference LOCAL_FREE runtime adapter: adaptive research route -> incumbent Plan-4 serving.

Host-facing composition only. No provider registration, paid/external calls,
network, auto-retry, factual certification or untrusted permission grants.
"""
from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from typing import Callable

from tools.plan4_multimodel_serving import MultiModelServing

from twelve_six_agent_runtime.adaptive_research_routing import (
    ModelOutcome, ResourceReading, RouteDecision, RouteError, RoutePolicy,
    RouteState, Specialist, accept_outcome, select_next,
)

_SCHEME = "12-6.plan4-multimodel-serving.v1"
_NAME = re.compile(r"[A-Za-z0-9_-]{1,64}\Z")


@dataclass(frozen=True, slots=True)
class VerifiedNextStep:
    """Trusted external verifier's conclusion; not text generated by a model."""

    next_capability: str
    measurable_progress: bool

    def validate(self) -> None:
        if type(self.next_capability) is not str or not 1 <= len(self.next_capability) <= 128:
            raise RouteError("invalid verified next capability")
        if type(self.measurable_progress) is not bool:
            raise RouteError("invalid verified progress flag")


@dataclass(frozen=True, slots=True)
class RouteExecution:
    status: str
    decision: RouteDecision
    state: RouteState
    reply: dict | None


def _digest(value: object) -> str:
    raw = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False)
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def route_local_generation(
    state: RouteState, members: tuple[Specialist, ...],
    policy: RoutePolicy, resources: ResourceReading,
    serving: MultiModelServing, *, prompt: str, max_new_tokens: int,
    verify: Callable[[dict], VerifiedNextStep | None],
) -> RouteExecution:
    """Invoke at most ONE already-admitted local role, then require host verification.

    The host alone owns policy, ModelServing publication and verifier callback.
    A provider failure yields a hard, explicit failure; never replay a call
    whose external completion state could be ambiguous.
    """
    if type(serving) is not MultiModelServing:
        raise RouteError("canonical Plan-4 serving plane required")
    if type(prompt) is not str or not 1 <= len(prompt) <= 8192:
        raise RouteError("bounded prompt required")
    if type(max_new_tokens) is not int or not 1 <= max_new_tokens <= 512:
        raise RouteError("bounded generation requested")
    if not callable(verify):
        raise RouteError("trusted verifier required")
    decision = select_next(state, members, policy, resources)
    if decision.status != "SELECTED":
        return RouteExecution(decision.status, decision, state, None)
    specialist = next(x for x in members if x.node_id == decision.node_id)
    # The host must approve other providers in a distinct, separately reviewed
    # adapter. This reference never bills or egresses model prompts.
    if specialist.provider != "local" or specialist.max_charge_microunits != 0:
        raise RouteError("only authorized free local specialists are supported")
    if _NAME.fullmatch(specialist.node_id) is None:
        raise RouteError("serving role name incompatible")
    catalog = serving.dispatch({"schema": _SCHEME, "op": "catalog", "args": {}})
    if catalog.get("ok") is not True:
        raise RouteError("serving catalog unavailable")
    matches = [slot for slot in catalog["result"]["slots"] if slot["role"] == specialist.node_id]
    if len(matches) != 1:
        raise RouteError("role must bind exactly one pinned slot")
    slot = matches[0]
    if slot["identity"]["model_weights_sha256"] != specialist.model_sha256:
        raise RouteError("serving model weight identity drift")
    if "generate" not in slot["capabilities"]:
        raise RouteError("admitted slot lacks generation capability")

    request_id = "r" + _digest({"task": state.task_id, "revision": state.revision})[:28]
    reply = serving.dispatch({"schema": _SCHEME, "op": "generate",
                              "args": {"request_id": request_id,
                                       "role": specialist.node_id,
                                       "prompt": prompt,
                                       "config": {"max_new_tokens": max_new_tokens},
                                       "failover": False}})
    if reply.get("ok") is not True:
        # Failure may be after a real provider side effect. The host reconciles.
        return RouteExecution("SERVING_FAILED_NO_RETRY", decision, state, reply)
    chosen = reply.get("selected", {})
    if (chosen.get("role") != specialist.node_id
            or chosen.get("slot_id") != slot["slot_id"]
            or chosen.get("identity") != slot["identity"]):
        raise RouteError("serving selected unpinned model")
    trusted = verify(reply)
    if trusted is None:
        return RouteExecution("UNVERIFIED", decision, state, reply)
    if type(trusted) is not VerifiedNextStep:
        raise RouteError("untrusted verifier verdict")
    trusted.validate()
    evidence_digest = _digest(reply)
    outcome = ModelOutcome(
        task_id=state.task_id, node_id=specialist.node_id,
        receipt_id="receipt-" + request_id,
        evidence_sha256=evidence_digest, charged_microunits=0,
        next_capability=trusted.next_capability,
        measurable_progress=trusted.measurable_progress,
    )
    updated = accept_outcome(state, decision, outcome, members, policy, resources,
                             lambda _: True)
    return RouteExecution("VERIFIED_ROUTE_ADVANCED", decision, updated, reply)
